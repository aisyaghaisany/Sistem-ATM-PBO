
public class Nasabah {

    private String nama;
    private String nomorRekening;

    public Nasabah(String nama, String nomorRekening) {
        this.nama = nama;
        this.nomorRekening = nomorRekening;
    }

    public String getNama() {
        return nama;
    }

    public String getNomorRekening() {
        return nomorRekening;
    }
}
